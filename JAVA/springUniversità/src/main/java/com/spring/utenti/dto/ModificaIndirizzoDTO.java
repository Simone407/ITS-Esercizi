package com.spring.utenti.dto;

public class ModificaIndirizzoDTO {

	private String matricola;
	private String nuovoIndirizzo;

	public ModificaIndirizzoDTO() {
	}

	public String getMatricola() {
		return matricola;
	}

	public void setMatricola(String matricola) {
		this.matricola = matricola;
	}

	public String getNuovoIndirizzo() {
		return nuovoIndirizzo;
	}

	public void setNuovoIndirizzo(String nuovoIndirizzo) {
		this.nuovoIndirizzo = nuovoIndirizzo;
	}
}
